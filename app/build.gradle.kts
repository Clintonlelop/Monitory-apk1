// The empty placeholder artifact com.google.guava:listenablefuture:
// 9999.0-empty-to-avoid-conflict-with-guava (pulled transitively by some
// Google libraries) beats any real 1.x version in Gradle conflict resolution
// and ships zero classes, which breaks androidx.concurrent.futures at runtime.
// Force the real interface jar regardless of what transitively requests it.
configurations.configureEach {
    resolutionStrategy {
        force("com.google.guava:listenablefuture:1.0")
    }
