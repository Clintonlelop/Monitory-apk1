android {
    namespace = "com.example"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.aistudio.devicemanager.rxqp"
        minSdk = 26
        targetSdk = 34
        versionCode = 1
        versionName = "1.0.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    val releaseKeystorePath = System.getenv("CM_KEYSTORE_PATH")
        ?: System.getenv("ANDROID_KEYSTORE_FILE")
    val releaseKeystorePassword = System.getenv("CM_KEYSTORE_PASSWORD")
        ?: System.getenv("ANDROID_KEYSTORE_PASSWORD")
    val releaseKeyAlias = System.getenv("CM_KEY_ALIAS")
        ?: System.getenv("ANDROID_KEYSTORE_KEY_ALIAS")
    val releaseKeyPassword = System.getenv("CM_KEY_PASSWORD")
        ?: System.getenv("ANDROID_KEYSTORE_KEY_PASSWORD")

    signingConfigs {
        // Debug key: decoded from $DEBUG_KEYSTORE_BASE64 in CI (or generated by
        // the CI script when absent). No keystore material is committed.
        create("debugConfig") {
            storeFile = file("${rootDir}/debug.keystore")
            storePassword = System.getenv("DEBUG_KEYSTORE_PASSWORD") ?: "android"
            keyAlias = System.getenv("DEBUG_KEY_ALIAS") ?: "androiddebugkey"
            keyPassword = System.getenv("DEBUG_KEY_PASSWORD") ?: "android"
        }
        // Release key: supplied via secure environment variables on CI/CD.
        // Without them the release build falls back to the debug key so the
        // pipeline still produces a verifiable artifact (documented in
        // codemagic.yaml — not production-ready for store distribution).
        create("releaseConfig") {
            val envPath = releaseKeystorePath
            val store = if (envPath != null) file(envPath) else file("${rootDir}/release.keystore")
            storeFile = store
            storePassword = releaseKeystorePassword
            keyAlias = releaseKeyAlias
            keyPassword = releaseKeyPassword
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            val releaseKs = signingConfigs.getByName("releaseConfig")
            val hasReleaseKey = releaseKs.storeFile?.exists() == true &&
                !releaseKs.storePassword.isNullOrEmpty() &&
                !releaseKs.keyAlias.isNullOrEmpty() &&
                !releaseKs.keyPassword.isNullOrEmpty()
            if (System.getenv("REQUIRE_ANDROID_SIGNING") == "true" && !hasReleaseKey) {
                throw GradleException(
                    "REQUIRE_ANDROID_SIGNING=true but no complete release signing configuration was provided"
                )
            }
            signingConfig = if (hasReleaseKey) {
                releaseKs
            } else {
                signingConfigs.getByName("debugConfig")
            }
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
        debug {
            isMinifyEnabled = false
            signingConfig = signingConfigs.getByName("debugConfig")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
        }
    }
}

