    // transitively via androidx.activity). Its writeProfile() path statically
    // initializes androidx.profileinstaller.ProfileVerifier, which creates a
    // ResolvableFuture -> AbstractResolvableFuture (androidx.concurrent:
    // concurrent-futures) implementing com.google.common.util.concurrent.
    // ListenableFuture. On release builds that chain was left unresolved
    // (java.lang.NoClassDefFoundError: androidx.concurrent.futures.
    // AbstractResolvableFuture at ProfileInstaller.writeProfile), because the
    // futures classes are not referenced by app code and can be dropped by
    // shrinking, and because com.google.guava:listenablefuture can resolve to
    // the intentionally-empty 9999.0 placeholder jar instead of the real 1.0
    // interface jar. Declare the whole chain explicitly so it is always
    // packaged. See proguard-rules.pro for the matching shrinker keeps.
    implementation(libs.androidx.profileinstaller)
    implementation(libs.androidx.concurrent.futures)
    implementation(libs.guava.listenablefuture)

